"""Regenerate the README "Model performance" section from the MLflow store.

The results table is a *derived* artifact rather than hand-maintained prose: run
this after any training run and the documented numbers match what the MLflow UI
shows.

    python scripts/sync_results.py            # rewrite README.md in place
    python scripts/sync_results.py --check    # exit 1 if README is out of date (CI-friendly)

"""

import argparse
import sys
from pathlib import Path

import mlflow
import yaml
from mlflow.client import MlflowClient
from mlflow.entities import ViewType

REPO_ROOT = Path(__file__).resolve().parents[1]
README = REPO_ROOT / "README.md"
TRACKING_URI = "sqlite:///mlflow.db"
BEGIN = "<!-- BEGIN RESULTS (generated by scripts/sync_results.py -- do not edit by hand) -->"
END = "<!-- END RESULTS -->"

# How the logged `model` param is spelled out in prose.
ARCH_LABELS = {
    "SimpleCNN": "SimpleCNN (from scratch)",
    "simple_cnn": "SimpleCNN (from scratch)",
    "resnet18": "ResNet18 transfer (frozen backbone)",
}
NUMBER_WORDS = {1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six", 7: "Seven", 8: "Eight"}


def load_runs():
    """Active runs for the configured experiment, oldest first."""
    cfg = yaml.safe_load((REPO_ROOT / "params.yaml").read_text(encoding="utf-8"))
    experiment_name = cfg["train"]["experiment_name"]

    mlflow.set_tracking_uri(TRACKING_URI)
    client = MlflowClient()
    experiment = client.get_experiment_by_name(experiment_name)
    if experiment is None:
        sys.exit(f"No MLflow experiment named {experiment_name!r} in {TRACKING_URI}")

    runs = client.search_runs(
        experiment_ids=[experiment.experiment_id],
        run_view_type=ViewType.ACTIVE_ONLY,
        order_by=["attributes.start_time ASC"],
    )
    if not runs:
        sys.exit(f"Experiment {experiment_name!r} has no active runs")
    return runs


def summarize(runs):
    """Flatten runs into row dicts, tagging any that exactly reproduce an earlier one."""
    rows, seen = [], {}
    for index, run in enumerate(runs, start=1):
        params, metrics = run.data.params, run.data.metrics
        arch = params.get("model", params.get("arch", "?"))
        row = {
            "index": index,
            "name": run.info.run_name,
            "arch": ARCH_LABELS.get(arch, arch),
            "lr": params.get("lr", "?"),
            "epochs": params.get("epochs", "?"),
            "test_acc": metrics.get("test_acc"),
            "test_f1": metrics.get("test_f1"),
            # A run counts as a repeat only if its config *and* its results match
            # an earlier one -- same hyperparameters with different numbers would
            # mean the seeding is not actually deterministic.
            "duplicate_of": None,
        }
        signature = (arch, row["lr"], row["epochs"], round(row["test_acc"], 12))
        row["duplicate_of"] = seen.get(signature)
        seen.setdefault(signature, index)
        rows.append(row)
    return rows


def render(rows):
    total = len(rows)
    repeats = [r for r in rows if r["duplicate_of"]]
    distinct = total - len(repeats)
    best = max(rows, key=lambda r: r["test_acc"])

    count = NUMBER_WORDS.get(total, str(total))
    caption = (
        f"{count} tracked MLflow runs on the same 3,000-image-per-class split "
        f"(80/10/10, 224x224 RGB, augmented training set)"
    )
    if repeats:
        caption += (
            f" -- {NUMBER_WORDS.get(distinct, distinct).lower()} distinct configurations, plus "
            f"{'an exact re-run' if len(repeats) == 1 else f'{len(repeats)} exact re-runs'} "
            f"kept as the reproducibility check"
        )
    caption += ":"

    lines = [
        BEGIN,
        "",
        caption,
        "",
        "| Run | MLflow run | Architecture | LR | Epochs | Test accuracy | Test F1 |",
        "| --- | ---------- | ------------ | -- | ------ | ------------- | ------- |",
    ]
    for row in rows:
        cells = [
            str(row["index"]),
            f"`{row['name']}`",
            row["arch"],
            row["lr"],
            row["epochs"],
            f"{row['test_acc']:.3f}",
            f"{row['test_f1']:.3f}",
        ]
        if row is best:  # the promoted model gets the emphasis
            cells = [f"**{cell}**" for cell in cells]
        lines.append("| " + " | ".join(cells) + " |")

    notes = [
        f"Run {best['index']} (`{best['name']}`) is the deployed model (`models/model.pt`). "
        "Freezing the ImageNet backbone means only the classifier head trains, so it "
        "converges in fewer epochs *and* less wall-clock time per epoch than the "
        "from-scratch baseline."
    ]
    for row in repeats:
        notes.append(
            f"Run {row['index']} (`{row['name']}`) repeats the configuration of run "
            f"{row['duplicate_of']} (`{rows[row['duplicate_of'] - 1]['name']}`) as a reproducibility "
            "check: under `seed: 42` it matches that run's metrics to every decimal place, which is "
            "the evidence that training is deterministic."
        )

    for note in notes:
        lines += ["", note]
    lines += ["", END]
    return "\n".join(lines)


def splice(text, block):
    start, end = text.find(BEGIN), text.find(END)
    if start == -1 or end == -1:
        sys.exit(f"README.md is missing the {BEGIN!r} / {END!r} markers")
    return text[:start] + block + text[end + len(END):]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify README matches mlflow.db instead of rewriting it",
    )
    args = parser.parse_args()

    current = README.read_text(encoding="utf-8")
    updated = splice(current, render(summarize(load_runs())))

    if args.check:
        if updated != current:
            sys.exit("README.md is out of date with mlflow.db -- run: python scripts/sync_results.py")
        print("README.md matches mlflow.db")
        return

    if updated == current:
        print("README.md already matches mlflow.db")
        return
    README.write_text(updated, encoding="utf-8")
    print("README.md updated from mlflow.db")


if __name__ == "__main__":
    main()
